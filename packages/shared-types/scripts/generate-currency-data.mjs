/**
 * Writes src/currency/data.ts: the currency table every Rekey surface reads.
 *
 * Names and the list of codes come from this runtime's `Intl`; exponents come
 * from `Intl` corrected to ISO 4217; countries come from the hand-maintained
 * map beside this file. The output is checked in, so a browser bundle needs no
 * `Intl.supportedValuesOf` and two Node versions cannot disagree.
 *
 *   node scripts/generate-currency-data.mjs
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { COUNTRY_CURRENCY, ISO_EXPONENT_CORRECTIONS, ISO_NON_TWO_DECIMAL } from './country-currency.mjs';

const names = new Intl.DisplayNames(['en'], { type: 'currency' });
const codes = Intl.supportedValuesOf('currency');

function exponentOf(code) {
  const corrected = ISO_EXPONENT_CORRECTIONS[code];
  if (corrected !== undefined) return corrected;
  return new Intl.NumberFormat('en', { style: 'currency', currency: code }).resolvedOptions().maximumFractionDigits;
}

const countriesOf = new Map(codes.map((code) => [code, []]));
for (const [country, currency] of Object.entries(COUNTRY_CURRENCY)) {
  if (currency === null) continue;
  const list = countriesOf.get(currency);
  if (!list) throw new Error(`${country} maps to ${currency}, which this runtime's Intl does not list`);
  list.push(country);
}

const rows = codes.map((code) => {
  const exponent = exponentOf(code);
  const expected = ISO_NON_TWO_DECIMAL[code] ?? 2;
  if (exponent !== expected) {
    throw new Error(`${code}: got exponent ${exponent}, ISO 4217 says ${expected}. Add it to ISO_EXPONENT_CORRECTIONS.`);
  }
  // The runtime writes year ranges with a long dash; a plain hyphen reads the same.
  const name = names.of(code).replace(/[\u2013\u2014]/g, '-');
  return { code, name, exponent, countries: countriesOf.get(code).sort() };
});

const lines = rows.map(
  (row) =>
    `  ${row.code}: { code: '${row.code}', name: '${row.name.replace(/'/g, "\\'")}', exponent: ${row.exponent}, countries: [${row.countries
      .map((c) => `'${c}'`)
      .join(', ')}] },`,
);

const out = `// Generated by scripts/generate-currency-data.mjs. Do not edit by hand.

export interface CurrencyRecord {
  /** ISO 4217 alphabetic code, upper case. */
  code: string;
  /** English name. */
  name: string;
  /** ISO 4217 minor-unit exponent: a stored amount is this many decimal places below one unit. */
  exponent: 0 | 2 | 3;
  /** ISO 3166-1 alpha-2 countries where this is the local currency. */
  countries: readonly string[];
}

export const CURRENCY_TABLE: Readonly<Record<string, CurrencyRecord>> = {
${lines.join('\n')}
};
`;

const target = path.join(path.dirname(fileURLToPath(import.meta.url)), '../src/currency/data.ts');
writeFileSync(target, out);
console.log(`wrote ${rows.length} currencies to ${target}`);
